def _password_model():
    result = OrinDecisionAgent().apply_decision(
        CONF / "password-reset.model.json", RATE_LIMIT, "five-per-15m-per-address-and-origin")
    return deepcopy(result.model.document)


def _expense_model():
    return json.loads((CONF / "expense-approval.resolved.model.json").read_text(encoding="utf-8"))


def _poison(value, text):
    """Replace every free-text string except ids/claims the generator parses."""
    if isinstance(value, dict):
        return {k: (v if k in ("id", "claims", "kind", "status", "from", "to", "target", "source", "uses",
                               "capability", "state", "states", "type", "default")
                    else _poison(v, text)) for k, v in value.items()}
    if isinstance(value, list):
        return [_poison(v, text) for v in value]
    if isinstance(value, str):
        return text
    return value


def _exec(source):
    sentinel = {"INJECTED": []}
    code = compile(source, "<generated>", "exec")
    namespace = dict(sentinel, __name__="generated")
    exec(code, namespace)
    return namespace


class HostileModelTests(unittest.TestCase):
    def check(self, doc):
        model = SemanticModel(doc)
        source = gen.generate_source(model)
        ns = _exec(source)
        self.assertEqual(ns["INJECTED"], [])
        self.assertEqual(source, gen.generate_source(SemanticModel(doc)))
        self.assertRegex(ns["MODULE_ID"], r"^[A-Za-z0-9._/-]*$")
        for ch in "\u2028\u2029\x00":
            self.assertNotIn(ch, source)
        return source

    def test_hostile_module_id(self):
        for make in (_password_model, _expense_model):
            for text in HOSTILE:
                doc = make()
                if doc["module"]["id"] == gen.EXPENSE_MODULE_ID:
                    # keep routing id intact; hostile text goes in the other module fields
                    doc["module"]["name"] = text
                    doc["module"]["purpose"] = text
                else:
                    doc["module"]["id"] = text
                    doc["module"]["name"] = text
                self.check(doc)

    def test_hostile_free_text_everywhere(self):
        for make in (_password_model, _expense_model):
            for text in HOSTILE:
                self.check(_poison(make(), text))

    def test_hostile_module_id_is_sanitized_not_executed(self):
        doc = _password_model()
        doc["module"]["id"] = 'x"""\nINJECTED.append(1)\n"""#'
        source = self.check(doc)
        self.assertTrue(source.startswith('"""Generated by Orin codegen from model "x____INJECTED'))

    def test_template_placeholder_in_id_is_inert(self):
        doc = _password_model()
        doc["module"]["id"] = "@@TTL@@"
        source = self.check(doc)
        self.assertIn('MODULE_ID = "__TTL__"', source)

    def test_long_values_deterministic_and_bounded(self):
        doc = _password_model()
        doc["module"]["id"] = "m" * 100_000
        source = self.check(doc)
        self.assertLess(len(source), 50_000)

    def test_cli_round_trip_hostile(self):
        doc = _poison(_password_model(), HOSTILE[0])
        with tempfile.TemporaryDirectory(dir=Path(__file__).parent) as tmp:
            model_path = Path(tmp) / "m.json"
            model_path.write_text(json.dumps(doc), encoding="utf-8")
            target = gen.generate(model_path, Path(tmp) / "out")
            compile(target.read_text(encoding="utf-8"), str(target), "exec")


class MalformedModelTests(unittest.TestCase):
    def assert_refused(self, doc):
        with self.assertRaises(gen.GenerationError):
            gen.generate_source(SemanticModel(doc))

    def test_malformed_documents(self):
        base = _password_model()
        cases = []
        cases.append({})
        doc = deepcopy(base); doc["objects"] = "nope"; cases.append(doc)
        doc = deepcopy(base); doc["module"] = "nope"; cases.append(doc)
        doc = deepcopy(base); doc["module"] = None; cases.append(doc)
        doc = deepcopy(base)
        doc["objects"] = [o for o in doc["objects"] if o.get("id") != gen.WORKFLOW_ID]
        cases.append(doc)
        doc = deepcopy(base)
        for o in doc["objects"]:
            if o.get("id") == gen.EXPIRY_RULE_ID:
                o["claims"] = ["tokens never expire"]
        cases.append(doc)
        doc = deepcopy(base)
        for o in doc["objects"]:
            if o.get("id") == gen.RATE_LIMIT_RULE_ID:
                o["claims"] = "not a list"
        cases.append(doc)
        for doc in cases:
            with self.subTest(doc=str(doc)[:60]):
                self.assert_refused(doc)

    def test_cli_reports_clean_errors(self):
        with tempfile.TemporaryDirectory(dir=Path(__file__).parent) as tmp:
            bad = Path(tmp) / "bad.json"
            for text in ("{not json", "[]", "{}"):
                bad.write_text(text, encoding="utf-8")
                self.assertEqual(gen.main([str(bad), str(Path(tmp) / "out")]), 1)
            self.assertEqual(gen.main([str(Path(tmp) / "missing.json"), tmp]), 1)

    def test_unready_model_refused(self):
        doc = json.loads((CONF / "password-reset.model.json").read_text(encoding="utf-8"))
        self.assert_refused(doc)


